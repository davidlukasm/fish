"""Generate named wire columns from the shared protocol schema."""

from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parent


def outputs():
    schema = json.loads((ROOT / "protocol_schema.json").read_text())
    groups = schema["columns"]
    cpp = ["#pragma once", "#include <array>", "#include <cstddef>", "namespace fishsim {"]
    js = ["// Generated by schema.py from protocol_schema.json."]
    python = ['"""Generated by schema.py from protocol_schema.json."""']
    for group, names in groups.items():
        assert len(names) == len(set(names)), group
        assert all(re.fullmatch(r"[a-z][a-z0-9_]*", name) for name in names)
        title = "".join(part.capitalize() for part in group.split("_"))
        cpp.append(f"enum class {title}Column : std::size_t {{")
        cpp.extend(f"  {name} = {i}," for i, name in enumerate(names))
        cpp += [f"  count = {len(names)}", "};", f"namespace {group}_column {{"]
        cpp.extend(
            f"inline constexpr std::size_t {name} = {i};"
            for i, name in enumerate(names)
        )
        cpp += [f"inline constexpr std::size_t count = {len(names)};", "}"]
        js.append(f"export const {group.upper()} = Object.freeze({{")
        js.extend(f"  {name}: {i}," for i, name in enumerate(names))
        js += [f"  count: {len(names)}", "});"]
        python.append(f"\nclass {title}:")
        python.extend(f"    {name.upper()} = {i}" for i, name in enumerate(names))
        python.append(f"    COUNT = {len(names)}")
    for group, values in schema["values"].items():
        assert re.fullmatch(r"[a-z][a-z0-9_]*", group), group
        assert all(re.fullmatch(r"[a-z][a-z0-9_]*", name) for name in values)
        assert all(type(value) is int and 0 <= value <= 255 for value in values.values())
        assert len(values) == len(set(values.values())), group
        title = "".join(part.capitalize() for part in group.split("_"))
        cpp.append(f"namespace {group} {{")
        cpp.extend(f"inline constexpr int {key} = {value};" for key, value in values.items())
        if sorted(values.values()) == list(range(len(values))):
            cpp.append(f"inline constexpr int count = {len(values)};")
        cpp.append("}")
        js.append(f"export const {group.upper()} = Object.freeze(" + json.dumps(values) + ");")
        python.append(f"\nclass {title}:")
        python.extend(f"    {key.upper()} = {value}" for key, value in values.items())
        if sorted(values.values()) == list(range(len(values))):
            python.append(f"    COUNT = {len(values)}")
    for group, values in schema["constants"].items():
        assert re.fullmatch(r"[a-z][a-z0-9_]*", group), group
        assert all(re.fullmatch(r"[a-z][a-z0-9_]*", name) for name in values)
        title = "".join(part.capitalize() for part in group.split("_"))
        cpp.append(f"namespace {group} {{")
        for key, value in values.items():
            if isinstance(value, list):
                items = ", ".join(repr(float(v)) for v in value)
                cpp.append(
                    f"inline constexpr std::array<double, {len(value)}> {key}{{{items}}};"
                )
            else:
                kind = "int" if type(value) is int else "double"
                cpp.append(f"inline constexpr {kind} {key} = {value!r};")
        cpp.append("}")
        js.append(f"export const {group.upper()} = Object.freeze(" + json.dumps(values) + ");")
        python.append(f"\nclass {title}:")
        python.extend(
            f"    {key.upper()} = {tuple(value) if isinstance(value, list) else value!r}"
            for key, value in values.items()
        )
    # Named subsets of a column group, as column indices.
    for group, sets in schema["column_sets"].items():
        names = groups[group]
        title = "".join(part.capitalize() for part in group.split("_")) + "Set"
        cpp.append(f"namespace {group}_set {{")
        js.append(f"export const {group.upper()}_SET = Object.freeze({{")
        python.append(f"\nclass {title}:")
        for key, members in sets.items():
            assert re.fullmatch(r"[a-z][a-z0-9_]*", key), key
            indices = [names.index(m) for m in members]
            cpp.append(
                f"inline constexpr std::array<std::size_t, {len(indices)}> {key}{{"
                + ", ".join(map(str, indices))
                + "};"
            )
            js.append(f"  {key}: Object.freeze({json.dumps(indices)}),")
            python.append(f"    {key.upper()} = {tuple(indices)!r}")
        cpp.append("}")
        js.append("});")
    # The organ port each motor kind works through, in motor kind order.
    ports = schema["motor_ports"]
    assert len(ports) == len(schema["values"]["motor_kind"])
    port_values = [schema["values"]["organ_port"][name] for name in ports]
    cpp.append(
        f"inline constexpr std::array<int, {len(ports)}> motor_ports{{"
        + ", ".join("organ_port::" + name for name in ports)
        + "};"
    )
    js.append("export const MOTOR_PORTS = Object.freeze(" + json.dumps(port_values) + ");")
    python.append("\nMOTOR_PORTS = " + repr(tuple(port_values)))
    scales = schema["behavior_scales"]
    cpp.append("namespace behavior_scale {")
    cpp.extend(f"inline constexpr double {key} = {value};" for key, value in scales.items())
    cpp.append("}")
    js.append("export const BEHAVIOR_SCALE = Object.freeze(" + json.dumps(scales) + ");")
    python.append("\nclass BehaviorScale:")
    python.extend(f"    {key.upper()} = {value}" for key, value in scales.items())
    js.append("export function initialize(indices) {}")
    cpp.append("}")
    core = ["#pragma once", "#include <cstddef>", "namespace cppn { namespace output {"]
    core.extend(
        f"inline constexpr std::size_t {name} = {i};"
        for i, name in enumerate(groups["cppn_output"])
    )
    core += [
        f"inline constexpr std::size_t count = {len(groups['cppn_output'])};",
        "}}",
    ]
    # Sense and motor kinds of the body field, as the core's enums.
    field = ["#pragma once", "namespace field {"]
    for group, title, count in (
        ("sense_kind", "Sense", "SENSE_COUNT"),
        ("motor_kind", "Motor", "MOTOR_COUNT"),
    ):
        kinds = schema["values"][group]
        assert list(kinds.values()) == list(range(len(kinds))), group
        field.append(
            f"enum {title} {{ "
            + ", ".join("".join(p.capitalize() for p in name.split("_")) for name in kinds)
            + " };"
        )
        field.append(f"constexpr int {count} = {len(kinds)};")
    span = schema["constants"]["time_constant"]
    field.append("// Cell time constants run from TIME_CONSTANT_MIN steps over TIME_CONSTANT_SPAN times that.")
    field.append(f"constexpr double TIME_CONSTANT_MIN = {span['min_steps']}, TIME_CONSTANT_SPAN = {span['span']};")
    field.append("// A brain develops on at most MAX_WORKERS threads, like a tank.")
    field.append(f"constexpr int MAX_WORKERS = {schema['constants']['run_limit']['max_threads']};")
    field.append("}")
    result = {
        "colony-core/cppn/output_schema.hh": "\n".join(core) + "\n",
        "colony-core/field/sense_schema.hh": "\n".join(field) + "\n",
        "src/protocol_schema.hh": "\n".join(cpp) + "\n",
        "ui/schema.js": "\n".join(js) + "\n",
        "protocol_schema.py": "\n".join(python) + "\n",
    }
    result["protocol_schema.py"] += "\nSCENE_HEADER = " + repr(schema["scene_header"]) + "\n"
    # A scene bundle: its magic, then the size of each part, then the parts.
    bundle = schema["scene_bundle"]
    bundle = {**bundle, "header_bytes": len(bundle["magic"]) + bundle["size_bytes"] * len(bundle["parts"])}
    result["protocol_schema.py"] += "\nSCENE_BUNDLE = " + repr(bundle) + "\n"
    layouts = schema["render_records"]
    kinds = schema["render_kinds"]
    assert set(kinds) == set(layouts)
    sizes = {
        "u8": 1,
        "i8": 1,
        "u16": 2,
        "i16": 2,
        "u32": 4,
        "i32": 4,
        "i64": 8,
        "f32": 4,
    }
    header = schema["scene_header"]
    # Each header field reaches to the next one; the last to the end of the header.
    offsets = sorted(header["offsets"].items(), key=lambda item: item[1])
    widths = {
        name: (offsets[i + 1][1] if i + 1 < len(offsets) else header["bytes"]) - offset
        for i, (name, offset) in enumerate(offsets)
    }
    assert widths["magic"] == len(header["magic"])
    for tile in header["tiles"].values():
        tile["bytes"] = sizes[tile["type"]]
    h = [
        "#pragma once",
        "#include <array>",
        "#include <cstddef>",
        "namespace fishsim { namespace render_wire {",
        "enum class Type { u8, i8, u16, i16, u32, i32, i64, f32 };",
        "struct Field { Type type; std::size_t offset, size; double scale; };",
        f"inline constexpr unsigned version = {header['version']};",
        f"inline constexpr char magic[] = {json.dumps(header['magic'])};",
        f"inline constexpr std::size_t header_bytes = {header['bytes']};",
        f"inline constexpr double coordinate_units = {header['coordinate_units']};",
        f"inline constexpr std::size_t count_bytes = {header['count_bytes']};",
        f"inline constexpr std::size_t identity_bytes = {header['identity_bytes']};",
        f"inline constexpr double light_scale = {header['tiles']['light']['scale']};",
        f"inline constexpr char bundle_magic[] = {json.dumps(bundle['magic'])};",
        f"inline constexpr std::size_t bundle_size_bytes = {bundle['size_bytes']};",
        "namespace scene_offset {",
    ]
    h.extend(f"inline constexpr std::size_t {name} = {offset};" for name, offset in offsets)
    h.append("}")
    h.append("namespace scene_width {")
    h.extend(f"inline constexpr std::size_t {name} = {width};" for name, width in widths.items())
    h.append("}")
    h.append("namespace scene_flag {")
    h.extend(f"inline constexpr unsigned {name} = {bit};" for name, bit in header["flags"].items())
    h.append("}")
    js = [
        "// Generated by schema.py from protocol_schema.json.",
        "export const SCENE_HEADER = Object.freeze("
        + json.dumps({**header, "widths": widths})
        + ");",
        "export const SCENE_BUNDLE = Object.freeze(" + json.dumps(bundle) + ");",
        "export const RENDER_RECORDS = Object.freeze({",
    ]
    h.append(
        "enum class Kind { "
        + ", ".join(name.capitalize() + " = " + str(i) for i, name in enumerate(kinds))
        + ", Count = "
        + str(len(kinds))
        + " };"
    )
    h.append("namespace fish_flag {")
    h.extend(
        f"inline constexpr unsigned {name} = {value};"
        for name, value in schema["fish_flags"].items()
    )
    h.append("}")
    js.insert(
        1, "export const RENDER_KINDS = Object.freeze(" + json.dumps(kinds) + ");"
    )
    js.insert(
        2,
        "export const FISH_FLAGS = Object.freeze("
        + json.dumps(schema["fish_flags"])
        + ");",
    )
    for name in kinds:
        fields = layouts[name]
        assert len(fields) <= 64
        offset = 0
        h.append("namespace " + name + " {")
        for i, field in enumerate(fields):
            h.append(f"inline constexpr std::size_t {field['name']} = {i};")
        h.append(
            "inline constexpr std::array<Field, " + str(len(fields)) + "> fields = {{"
        )
        for field in fields:
            size = sizes[field["type"]]
            h.append(f"{{Type::{field['type']}, {offset}, {size}, {field['scale']}}},")
            field["offset"], field["bytes"] = offset, size
            offset += size
        h += ["}};", f"inline constexpr std::size_t bytes = {offset};", "}"]
        js.append(name + ": " + json.dumps(fields, separators=(",", ":")) + ",")
    h.append("}}")
    js.append("});")
    result["src/render_schema.hh"] = "\n".join(h) + "\n"
    result["ui/render_schema.js"] = "\n".join(js) + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    for name, content in outputs().items():
        path = ROOT / name
        matches = path.exists() and re.sub(r"\s+", "", path.read_text()) == re.sub(
            r"\s+", "", content
        )
        if args.write:
            if not matches:
                path.write_text(content)
        elif not matches:
            raise SystemExit(
                f"{name}: generated schema differs; run python3 schema.py --write"
            )


if __name__ == "__main__":
    main()
